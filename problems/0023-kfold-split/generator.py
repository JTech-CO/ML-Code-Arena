"""k-겹 분할 케이스.

나머지가 있는 경우를 중심에 둔다. 나누어떨어지는 케이스만 주면 나머지 배분 규칙이
한 번도 시험되지 않는다.

`k = n` 은 LOOCV(leave-one-out)다. 각 겹이 한 개씩이며 나머지가 0 이다.
`n % k == k - 1` 은 나머지가 가장 많은 경우로, 마지막 겹만 작다.
"""

SEED = 20260823

CASES = [
    (7, 3),
    (6, 3),
    (2, 2),
    (10, 10),
    (10, 3),
    (11, 3),
    (12, 3),
    (13, 5),
    (100, 7),
    (101, 7),
    (999, 10),
    (1000, 3),
]


def generate():
    for n, k in CASES:
        yield (n, k)
