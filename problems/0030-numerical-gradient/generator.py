"""수치 미분 케이스.

`h` 는 `1e-7` 이상만 쓴다. 더 작게 잡으면 `f(x+h) - f(x-h)` 가 자릿수 소실에 지배되어
**정답 구현끼리도 값이 갈린다** — 호너 방법과 거듭제곱 합은 반올림 오차가 다르기
때문이다. 그러면 이 문제는 "중심 차분을 구현했는가"가 아니라 "정확히 같은 순서로
계산했는가"를 묻게 된다.

2차 이하 다항식을 앞쪽에 둔다. 중심 차분이 `h` 와 무관하게 정확한 값을 주므로
손으로 검산할 수 있고, 전방 차분을 쓴 풀이가 `h` 만큼 어긋나 즉시 드러난다.

상수 함수(도함수 0)와 1차 함수(도함수 상수)도 경계다.
"""

import numpy as np

SEED = 20260830


def generate():
    yield (np.array([1.0, 0.0, 0.0]), np.array([1.0, 2.0]), 0.001)

    # 상수 — 도함수가 0 이다.
    yield (np.array([5.0]), np.array([-2.0, 0.0, 3.0]), 0.01)

    # 1차 — 도함수가 상수다.
    yield (np.array([3.0, -1.0]), np.array([-5.0, 0.0, 5.0]), 0.001)

    # 2차 — 중심 차분이 정확하다.
    yield (np.array([2.0, -3.0, 1.0]), np.array([-1.0, 0.0, 1.0, 2.0]), 0.1)

    rng = np.random.default_rng(SEED)

    for degree, n, h in [
        (3, 5, 1e-3),
        (4, 20, 1e-4),
        (5, 50, 1e-5),
        (2, 100, 1e-6),
        (3, 200, 1e-7),
        (6, 1000, 1e-5),
    ]:
        coeffs = rng.normal(size=degree + 1)
        # x 를 좁은 범위에 둔다. 고차 다항식에서 |x| 가 크면 f 가 커지고,
        # 그만큼 절대 반올림 오차가 커진다.
        yield (coeffs, rng.uniform(-2.0, 2.0, size=n), h)

    # 최고차 계수가 0 — 실질 차수가 낮다.
    yield (np.array([0.0, 0.0, 2.0, 1.0]), np.linspace(-3.0, 3.0, 30), 1e-4)
